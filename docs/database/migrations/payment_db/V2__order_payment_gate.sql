CREATE TABLE IF NOT EXISTS order_payment_gate (
 order_id BIGINT NOT NULL PRIMARY KEY COMMENT '订单内部编号',
 closing TINYINT NOT NULL DEFAULT 0 COMMENT '是否已开始关闭支付入口',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='支付单创建与关单的持久互斥屏障';
